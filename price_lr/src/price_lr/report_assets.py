# ---------------------------------------------------------------- figures
def _fig(h_in):
    plt = c.mpl()
    plt.rcParams.update({"font.size": 8, "axes.labelsize": 8, "legend.fontsize": 7.5,
                         "xtick.labelsize": 7.5, "ytick.labelsize": 7.5, "pdf.fonttype": 42})
    fig, ax = plt.subplots(figsize=(WIDTH_IN, h_in), facecolor="white")
    c.style(ax)
    ax.set_facecolor("white")
    ax.tick_params(labelsize=7.5)
    ax.grid(axis="y", color=c.GRID, linewidth=0.6)
    return plt, fig, ax


def _shade_stage3(ax, label=True):
    ax.axvspan(pd.Timestamp("2025-01-01"), pd.Timestamp("2026-11-01"), color=c.GRID, alpha=0.45, linewidth=0, zorder=0)
    if label:
        ax.text(pd.Timestamp("2025-01-15"), 0.97, "scored 11-18\n(Stage 3)", transform=ax.get_xaxis_transform(),
                va="top", fontsize=6.5, color=c.INK2)


