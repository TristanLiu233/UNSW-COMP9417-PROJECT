def num(v, dp=2, sign=False):
    """LaTeX text for a number; the manifest stores exactly this string."""
    s = f"{v:+.{dp}f}" if sign else f"{v:.{dp}f}"
    return s.replace("-", "$-$").replace("+", "$+$") if sign or v < 0 else s


class Manifest:
    def __init__(self):
        self.cells = []

    def cell(self, table, source, key, column, value, dp=2, sign=False):
        t = num(float(value), dp, sign)
        self.cells.append({"table": table, "text": t, "source": SRC[source], "key": key, "column": column,
                           "dp": dp, "sign": sign})
        return t


def header(name, sources, note=""):
    lines = [f"% {name} -- generated by `{CMD}`; do not edit numbers by hand.",
             "% Sources (results/price_lr/): " + ", ".join(SRC[s] for s in sources)]
    if note:
        lines.append(f"% {note}")
    return "\n".join(lines) + "\n"


def wrap(label, tabular, size="\\small"):
    return ("\\begin{table}[htbp]\n    \\centering\n    " + size + "\n    \\caption{} % P5: caption\n"
            f"    \\label{{{label}}}\n" + tabular + "\\end{table}\n")


# ---------------------------------------------------------------- 4.3: frozen LR, CUSUM alarms vs gap to b1
def table_s0_alarms(m):
    yd, yh = pd.read_csv(R("yearly")), pd.read_csv(R("h_yearly"))
    al = pd.read_csv(R("alarms")).set_index("year")["alarms"]
    mon = pd.concat([pd.read_csv(R("s0mon")), pd.read_csv(R("h_s0mon"))])
    recount = mon[mon["alarm"]].groupby(pd.to_datetime(mon[mon["alarm"]]["day"]).dt.year).size()
    assert recount.to_dict() == al.to_dict(), "alarm counts differ from the daily monitor files"
    rows = []
    for src_name, df in (("yearly", yd), ("h_yearly", yh)):
        for _, r in df.iterrows():
            y = int(r["year"])
            gap = r["S0_BalAcc"] - r["b1_BalAcc"]
            rows.append((str(y) + ("$^{*}$" if y == 2026 else ""), str(int(al.get(y, 0))),
                         m.cell("s0_alarms", src_name, y, "S0_BalAcc-b1_BalAcc", gap, sign=True)))
    m.cells.append({"table": "s0_alarms", "kind": "alarm_counts", "source": SRC["alarms"],
                    "values": {str(y): int(al.get(y, 0)) for y in range(2015, 2027)}})
    left, right = rows[:6], rows[6:]
    body = "".join("        " + " & ".join(a) + "\n        & " + " & ".join(b) + " \\\\\n" for a, b in zip(left, right))
    tab = ("    \\begingroup\n    \\setlength{\\tabcolsep}{3pt}\n"
           "    \\begin{tabular}{rrr@{\\qquad}rrr}\n        \\hline\n"
           "        Year & Alarms & S0$-b_1$ & Year & Alarms & S0$-b_1$ \\\\\n"
           "        \\hline\n" + body + "        \\hline\n    \\end{tabular}\n    \\endgroup\n"
           "    % S0 = frozen LR (fit through 2014-12-31, tau 0.42). S0-b1 = yearly BalAcc gap in percentage points,\n"
           "    % from unrounded scores (may differ by 0.01 from subtracting the rounded values in tab:p4years).\n"
           "    % Absolute yearly BalAcc: tab:p4years (2015-2024) and tab:p5-stage3 (2025-2026).\n"
           "    % Alarms: CUSUM on daily log loss, monitor only (no retraining), state carried from 2015-01-01.\n"
           "    % * 2026 covers January--October. 2025--2026 rows were scored on 2026-11-18 (stage3/), after the\n"
           "    %   2015--2024 rows; see stage3/decision.md section 5.\n")
    return header("Table: frozen-LR CUSUM alarms and yearly BalAcc gap to b1, 2015-2026",
                  ["yearly", "h_yearly", "alarms", "s0mon", "h_s0mon"]) + wrap("tab:p5-s0-alarms", tab)


# ---------------------------------------------------------------- 4.4: strategies 2015-2024
def table_strategies(m):
    cmp_ = pd.read_csv(R("cmp")).set_index("strategy")
    boot = pd.read_csv(R("boot"))
    bs = boot[boot["b"] == "S0"].set_index("a")
    desc = {"S0": "Frozen (no retraining)", "S1": "Every 2 years, expanding", "S2": "Every 2 years, 3-year sliding",
            "S3": "CUSUM alarm, expanding", "b1": "Previous day", "b7": "Previous week"}
    lines = []
    for s in STRATS + ["b1", "b7"]:
        r = cmp_.loc[s]
        retr = str(int(r["retrains_effective_in_dev"])) if s in STRATS else "--"
        if s in bs.index:
            ci = (m.cell("strategies", "boot", f"{s}-S0", "diff_pp", bs.loc[s, "diff_pp"], sign=True) + " ["
                  + m.cell("strategies", "boot", f"{s}-S0", "diff_lo", bs.loc[s, "diff_lo"], sign=True) + ", "
                  + m.cell("strategies", "boot", f"{s}-S0", "diff_hi", bs.loc[s, "diff_hi"], sign=True) + "]")
        else:
            ci = "--"
        lines.append(" & ".join([s.replace("b1", "$b_1$").replace("b7", "$b_7$"), desc[s], retr,
                                 m.cell("strategies", "cmp", s, "Acc", r["Acc"]),
                                 m.cell("strategies", "cmp", s, "BalAcc", r["BalAcc"]),
                                 m.cell("strategies", "cmp", s, "BalAcc_minus_b1", r["BalAcc_minus_b1"], sign=True)
                                 if s != "b1" else "--", ci]) + " \\\\")
    m.cells.append({"table": "strategies", "kind": "retrains", "source": SRC["cmp"],
                    "values": {s: int(cmp_.loc[s, "retrains_effective_in_dev"]) for s in STRATS}})
    s21 = boot[(boot["a"] == "S2") & (boot["b"] == "S1")].iloc[0]
    tab = ("    \\begingroup\n    \\setlength{\\tabcolsep}{4pt}\n    \\begin{tabular}{llrrrrl}\n        \\hline\n"
           "        & Retraining & Retrains & Acc & BA & BA$-b_1$ & BA$-$S0 [95\\% CI] \\\\\n        \\hline\n"
           + "".join("        " + l + "\n" for l in lines)
           + "        \\hline\n    \\end{tabular}\n    \\endgroup\n"
           "    % 2015-01-01 .. 2024-12-31, 3,653 market days, 175,344 slots. Retrains = models that took effect in\n"
           "    % this period (S1/S2 also retrained at 2024-12-31, effective 2025). CI: paired whole-day bootstrap,\n"
           f"    % 1000 draws, seed 0, one index matrix for all strategies. Not shown: S2-S1 = {s21['diff_pp']:+.2f} "
           f"[{s21['diff_lo']:+.2f}, {s21['diff_hi']:+.2f}] (contains 0).\n")
    return header("Table: LR retraining strategies vs frozen and baselines, 2015-2024", ["cmp", "boot", "models"]) \
        + wrap("tab:p5-strategies", tab)


# ---------------------------------------------------------------- 4.4: Stage 3 check 2025-2026
def table_stage3(m):
    h = pd.read_csv(R("h_cmp")).set_index("strategy")
    hy = pd.read_csv(R("h_yearly")).set_index("year")
    veto = json.load(open(R("veto")))
    assert veto["final_strategy"] == "S1" and not veto["P_below_b1"]
    lines = []
    for s in STRATS + ["b1", "b7"]:
        r = h.loc[s]
        if s in STRATS:
            mid = r["models_deployed"]
            assert ";" not in str(mid), "one model per strategy expected in 2025-2026"
            log = pd.read_csv(R("models")).set_index(["strategy", "model_id"])
            cut = log.loc[(s, mid), "cutoff"]
            assert float(log.loc[(s, mid), "tau"]) == float(r["taus_deployed"])
            model = f"{'Frozen, fit' if mid == 'LR_frozen' else 'Refit'} to {cut} ({float(r['taus_deployed']):.2f})"
        else:
            model = "--"
        lines.append(" & ".join([s.replace("b1", "$b_1$").replace("b7", "$b_7$"), model,
                                 m.cell("stage3", "h_cmp", s, "Acc", r["Acc"]),
                                 m.cell("stage3", "h_cmp", s, "BalAcc", r["BalAcc"]),
                                 m.cell("stage3", "h_yearly", 2025, f"{s}_BalAcc", hy.loc[2025, f"{s}_BalAcc"]),
                                 m.cell("stage3", "h_yearly", 2026, f"{s}_BalAcc", hy.loc[2026, f"{s}_BalAcc"]),
                                 m.cell("stage3", "h_cmp", s, "BalAcc_minus_b1", r["BalAcc_minus_b1"], sign=True)
                                 if s != "b1" else "--"]) + " \\\\")
    tab = ("    \\begingroup\n    \\setlength{\\tabcolsep}{4pt}\n    \\begin{tabular}{llrrrrr}\n        \\hline\n"
           "        & Model in use ($\\tau$) & Acc & BA & BA 2025 & BA 2026$^{*}$ & BA$-b_1$ \\\\\n        \\hline\n"
           + "".join("        " + l + "\n" for l in lines)
           + "        \\hline\n    \\end{tabular}\n    \\endgroup\n"
           "    % 2025-01-01 .. 2026-10-31, 669 market days, 32,112 slots. * January--October.\n"
           f"    % Veto rule (design 11.4): switch from P = {veto['P']} to R = {veto['R']} only if BA(P) < BA(b1) and\n"
           f"    % BA(R) >= BA(b1). Here BA(P) is not below b1, so the final strategy is {veto['final_strategy']}.\n"
           "    % These two years had been partly seen before (frozen LR scores; P4 chose the final tau on\n"
           "    % 2025-11..2026-10): first scoring of S1-S3 under the pre-registered rule, not an unseen test.\n")
    return header("Table: Stage 3 veto check, 2025-01-01 to 2026-10-31", ["h_cmp", "h_yearly", "veto", "models"]) \
        + wrap("tab:p5-stage3", tab)


